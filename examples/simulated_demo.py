"""Generate the example report with a SIMULATED model (no API key needed).

The fake model knows each answer with some per-question robustness, and picks
whether to answer correctly from a hash of the exact prompt text, so surface
wording changes its behavior the way a brittle model's would. This exists only
to show what the report looks like; it says nothing about any real model.

    python examples/simulated_demo.py
"""

import hashlib
import json
import random
from pathlib import Path

from flipcheck import run
from flipcheck.report import to_html

HERE = Path(__file__).resolve().parent
items = [json.loads(line) for line in (HERE / "questions.jsonl").read_text().splitlines() if line.strip()]
answers = {it["question"]: it["answer"] for it in items}
rng = random.Random(0)
robustness = {q: rng.choice([1.0, 1.0, 1.0, 0.9, 0.75, 0.55, 0.35]) for q in answers}
WRONG = {"4": "3", "23": "46", "1989": "1991", "391": "381", "97": "91", "12": "8", "50": "48", "3": "2"}


def simulated_model(prompt: str) -> str:
    q = next(q for q in answers if q.rstrip("?.").lower() in prompt.lower())
    h = int(hashlib.sha256(prompt.encode()).hexdigest(), 16) % 1000 / 1000
    gold = answers[q]
    reply = gold if h < robustness[q] else WRONG.get(gold, f"not {gold}" if gold in ("yes",) else "unsure")
    if gold == "yes" and reply != gold:
        reply = "no"
    return f"Let me think.\nAnswer: {reply}"


results, summary = run(items, simulated_model, n_variants=10, answer_type="free")
for k, v in summary.__dict__.items():
    print(f"{k:<22} {v if not isinstance(v, float) else round(v, 3)}")
out = HERE.parent / "docs" / "example_report.html"
out.parent.mkdir(exist_ok=True)
out.write_text(to_html(results, summary, "SIMULATED brittle model (demo only)",
                       "Generated by examples/simulated_demo.py. Not a real model."))
print(f"report: {out}")
